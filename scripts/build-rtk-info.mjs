/**
 * Builds src/data/rtkKanjiInfo.ts (the kanji deck's card backs) from
 * reference_files/heisig-kanjis.csv:
 *
 *   node scripts/build-rtk-info.mjs
 *
 * Per kanji: up to two on readings, up to two kun readings, and its components.
 * The CSV flattens components recursively and mixes in primitive aliases
 * ("water; water droplets; water pistol; every; reclining; mother; …"), so the
 * top-level parts are recovered greedily: keep a token only if it is another RTK
 * keyword, then skip the tokens that belong to that part's own component list.
 * For 海 that gives "water · every"; for 宣, "house · span".
 */
import { readFileSync, writeFileSync } from 'node:fs';

const CSV = 'reference_files/heisig-kanjis.csv';
const OUT = 'src/data/rtkKanjiInfo.ts';

// Minimal CSV parser (quoted fields may contain commas).
function parseCsv(text) {
  const rows = [];
  let row = [], field = '', quoted = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (ch === '"') quoted = false;
      else field += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ',') { row.push(field); field = ''; }
    else if (ch === '\n') { row.push(field); rows.push(row); row = []; field = ''; }
    else if (ch !== '\r') field += ch;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  return rows;
}

const [header, ...body] = parseCsv(readFileSync(CSV, 'utf8'));
const col = Object.fromEntries(header.map((h, i) => [h, i]));
const rows = body
  .filter((r) => /^\d+$/.test((r[col.id_6th_ed] ?? '').trim()) && Number(r[col.id_6th_ed]) <= 2200) // RTK volume 1
  .map((r) => ({
    kanji: r[col.kanji],
    n: Number(r[col.id_6th_ed]),
    keyword: (r[col.keyword_6th_ed] || '').trim().toLowerCase(),
    components: (r[col.components] || '').split(';').map((s) => s.trim().toLowerCase()).filter(Boolean),
    on: (r[col.on_reading] || '').split(';').map((s) => s.trim()).filter(Boolean),
    kun: (r[col.kun_reading] || '').split(';').map((s) => s.trim()).filter(Boolean),
  }))
  .sort((a, b) => a.n - b.n);

const byKeyword = new Map(rows.map((r) => [r.keyword, r]));

function topLevelParts(r) {
  const parts = [];
  const toks = r.components;
  for (let i = 0; i < toks.length; i++) {
    const part = byKeyword.get(toks[i]);
    if (!part || part.kanji === r.kanji) continue;
    if (!parts.includes(toks[i])) parts.push(toks[i]);
    // Skip what follows that is part of this component's own breakdown.
    const inner = new Set(part.components);
    while (i + 1 < toks.length && inner.has(toks[i + 1])) i++;
  }
  return parts.slice(0, 4);
}

// Kun readings: drop prefix/suffix forms ("-か.ける"), turn the okurigana dot into
// plain kana (か.ける → かける), dedupe, keep two.
function cleanKun(kun) {
  const out = [];
  for (const k of kun) {
    if (k.startsWith('-') || k.endsWith('-')) continue;
    const plain = k.replace(/\./g, '');
    if (!out.includes(plain)) out.push(plain);
  }
  return out.slice(0, 2);
}

const entries = rows.map((r) => {
  const info = [r.on.slice(0, 2).join('・'), cleanKun(r.kun).join('・'), topLevelParts(r).join(' · ')];
  return `  ${JSON.stringify(r.kanji)}: ${JSON.stringify(info)},`;
});

writeFileSync(OUT, `// Generated by scripts/build-rtk-info.mjs from reference_files/heisig-kanjis.csv — do not edit.
// The RTK kanji deck's card backs: [on readings, kun readings, components].
// Loaded lazily by the kanji deck so it stays out of the main bundle.

export type KanjiInfo = [on: string, kun: string, parts: string];

export const rtkKanjiInfo: Record<string, KanjiInfo> = {
${entries.join('\n')}
};
`);
console.log(`wrote ${OUT}: ${rows.length} kanji`);
for (const k of ['海', '宣', '掛', '捗', '研', '一', '影']) {
  const r = rows.find((x) => x.kanji === k);
  if (r) console.log(' ', k, r.keyword, '|', r.on.slice(0, 2).join('・'), '|', cleanKun(r.kun).join('・'), '|', topLevelParts(r).join(' · '));
}
